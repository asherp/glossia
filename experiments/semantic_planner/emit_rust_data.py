#!/usr/bin/env python3
"""
Convert the experiment dataset (data/noun_classes_bip39.yaml + verb_frames_bip39.yaml)
into the production file the Rust generator loads: languages/english/semantics.yaml.

Output format (top-level classes; per-verb expanded frames):

  classes:
    clock: thing
    captain: animate
  frames:
    discover: { subj: [animate], obj: [abstract, thing, place] }
    exist:    { subj: any, obj: any }

Top-level classes: animate / agentive / thing / place / abstract.
Run after build_data.py.  python3 emit_rust_data.py
"""
import os
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
OUT = os.path.join(HERE, "..", "..", "languages", "english", "semantics.yaml")


def main():
    nd = yaml.safe_load(open(os.path.join(DATA, "noun_classes_bip39.yaml")))["nouns"]
    vf = yaml.safe_load(open(os.path.join(DATA, "verb_frames_bip39.yaml")))
    arch = vf["archetypes"]

    classes = {w: nd[w]["class"].split("/")[0] for w in sorted(nd)}   # top-level
    frames = {}
    for w in sorted(vf["verbs"]):
        a = arch[vf["verbs"][w]["archetype"]]
        frames[w] = {"subj": a["subj"], "obj": a["obj"]}

    with open(OUT, "w") as f:
        f.write("# Semantic data for the English generator. Generated by\n"
                "# experiments/semantic_planner/emit_rust_data.py from the WordNet-\n"
                "# assisted dataset. Consumed by src/generator/semantics.rs.\n"
                "#\n"
                "# classes: payload word -> top-level semantic class\n"
                "#          (animate | agentive | thing | place | abstract)\n"
                "# frames:  verb -> subject/object selectional restrictions\n"
                "#          (list of allowed classes, or 'any')\n"
                "#\n"
                "# Used only to softly bias sentence planning toward semantic\n"
                "# coherence; payload words are never dropped or reordered, so\n"
                "# decoding is unaffected regardless of this file.\n")
        # Disable YAML anchors/aliases: archetypes share list objects, which
        # would emit as *id refs — keep the file plain for the Rust loader.
        class NoAlias(yaml.SafeDumper):
            def ignore_aliases(self, data):
                return True
        yaml.dump({"classes": classes, "frames": frames},
                  f, Dumper=NoAlias, sort_keys=True, default_flow_style=None, width=100)

    print(f"wrote {OUT}")
    print(f"  {len(classes)} noun classes, {len(frames)} verb frames")


if __name__ == "__main__":
    main()
