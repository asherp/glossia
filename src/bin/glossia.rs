/// Apply highlighting to generated text based on highlight_mode.
/// Preserves embedded newlines (e.g., from CS grammar's Conj "\n" cover words)
/// by processing each line independently.
fn apply_highlighting(
    text: &str,
    payload_set: &HashSet<String>,
    payload: &[PayloadTok],
    highlight_mode: HighlightMode,
    merkle_set: Option<&HashSet<String>>,
    merkle_highlight_mode: Option<HighlightMode>,
) -> String {
    // Process each line independently to preserve embedded newlines
    // (e.g., ASCII armor header/body/footer separation via Conj "\n" cover words)
    text.split('\n')
        .map(|line| {
            let words: Vec<&str> = line.split_whitespace().collect();
            if words.is_empty() {
                return String::new();
            }

            if highlight_mode == HighlightMode::Madlib {
                // For madlib mode, replace payload words with [POS] placeholders
                words.iter().map(|word| {
                    let word_clean = normalize_token_for_bip39(word);
                    let is_payload = !word_clean.is_empty() && payload_set.contains(&word_clean);
                    let is_merkle = merkle_set.map(|s| !word_clean.is_empty() && s.contains(&word_clean)).unwrap_or(false);

                    if is_payload || is_merkle {
                        // Find the payload token to get its POS tag
                        if let Some(payload_tok) = payload.iter().find(|t| t.word.to_lowercase() == word_clean) {
                            // Use the first allowed POS tag for madlib
                            if let Some(&first_pos) = payload_tok.allowed.iter().next() {
                                let pos_str = first_pos.as_str();
                                // Preserve punctuation
                                let punct: String = word.chars().filter(|c| !c.is_alphabetic()).collect();
                                format!("[{}]{}", pos_str, punct)
                            } else {
                                word.to_string()
                            }
                        } else {
                            word.to_string()
                        }
                    } else {
                        word.to_string()
                    }
                }).collect::<Vec<String>>().join(" ")
            } else {
                words.iter().map(|word| {
                    let word_clean = normalize_token_for_bip39(word);
                    let is_payload = !word_clean.is_empty() && payload_set.contains(&word_clean);
                    let is_merkle = merkle_set.map(|s| !word_clean.is_empty() && s.contains(&word_clean)).unwrap_or(false);

                    if is_payload {
                        match highlight_mode {
                            HighlightMode::None => word.to_string(),
                            HighlightMode::Bars => wrap_payload_with_bars(word),
                            HighlightMode::Color(color) => wrap_payload_with_color(word, color),
                            HighlightMode::Madlib => unreachable!(), // Handled above
                        }
                    } else if is_merkle {
                        // Use merkle highlight mode if specified, otherwise don't highlight
                        match merkle_highlight_mode {
                            Some(HighlightMode::None) => word.to_string(),
                            Some(HighlightMode::Bars) => wrap_payload_with_bars(word),
                            Some(HighlightMode::Color(color)) => wrap_payload_with_color(word, color),
                            Some(HighlightMode::Madlib) => word.to_string(), // Madlib doesn't apply to merkle words
                            None => word.to_string(), // No merkle highlighting specified
                        }
                    } else {
                        word.to_string()
                    }
                }).collect::<Vec<String>>().join(" ")
            }
        })
        .collect::<Vec<String>>()
        .join("\n")
}


/// Compute k candidates based on the length mode.
/// Returns a vector of k values to try in order.
#[cfg(test)]
fn compute_k_candidates<R: Rng>(
    rng: &mut R,
    cache: &SequenceCache,
    start_symbol: &str,
    k_min: usize,
    k_max: usize,
    length_mode: SentenceLengthMode,
    require_prefix: bool,
) -> Vec<usize> {
    match length_mode {
        SentenceLengthMode::Compact => {
            // Compact mode: try k from k_min to k_max, shortest first
            let k_start = if require_prefix { k_min + 1 } else { k_min };
            (k_start..=k_max).collect()
        }
        SentenceLengthMode::Natural => {
            // Natural mode: sample k from grammar's length distribution
            // Respect k_min as a floor, but sample naturally above it
            let natural_k_start = if require_prefix { k_min.max(2) } else { k_min.max(1) };
            
            // Compute weights for each k >= k_min
            let mut k_weights: Vec<(usize, f64)> = Vec::new();
            for k in natural_k_start..=k_max {
                if let Some(sequences) = cache.get(start_symbol, k) {
                    let weight: f64 = if require_prefix {
                        sequences.iter()
                            .filter(|seq_prob| !seq_prob.sequence.is_empty() && seq_prob.sequence[0] == Pos::Prefix)
                            .map(|seq_prob| seq_prob.probability)
                            .sum()
                    } else {
                        sequences.iter()
                            .map(|seq_prob| seq_prob.probability)
                            .sum()
                    };
                    if weight > 0.0 {
                        k_weights.push((k, weight));
                    }
                }
            }
            
            if k_weights.is_empty() {
                // Fallback to compact mode if no weights found
                let k_start = if require_prefix { k_min + 1 } else { k_min };
                return (k_start..=k_max).collect();
            }
            
            // Sample one k from the distribution
            let total_weight: f64 = k_weights.iter().map(|(_, w)| w).sum();
            if total_weight <= 0.0 {
                // Fallback to compact mode if total weight is zero
                let k_start = if require_prefix { k_min + 1 } else { k_min };
                return (k_start..=k_max).collect();
            }
            
            let mut r = rng.gen::<f64>() * total_weight;
            let mut sampled_k = None;
            for (k, weight) in &k_weights {
                if r <= *weight {
                    sampled_k = Some(*k);
                    break;
                }
                r -= weight;
            }
            let sampled_k = sampled_k.unwrap_or_else(|| k_weights[0].0);
            
            // Build candidate list:
            // 1. Sampled k first
            // 2. Remaining k's in descending weight order
            // 3. Compact fallback (k_min..=k_max) for robustness
            
            let mut candidates = vec![sampled_k];
            
            // Add remaining k's in descending weight order (excluding sampled_k)
            let mut remaining: Vec<(usize, f64)> = k_weights.iter()
                .filter(|(k, _)| *k != sampled_k)
                .cloned()
                .collect();
            remaining.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
            candidates.extend(remaining.into_iter().map(|(k, _)| k));
            
            // Add compact fallback for robustness (only k's not already in candidates)
            // Still respect k_min for the fallback to ensure we don't miss any valid k values
            let candidates_set: std::collections::HashSet<usize> = candidates.iter().cloned().collect();
            let k_start = if require_prefix { k_min + 1 } else { k_min };
            for k in k_start..=k_max {
                if !candidates_set.contains(&k) {
                    candidates.push(k);
                }
            }
            
            candidates
        }
    }
}

/// Parse an endpoint string into an Endpoint value.
///
/// Supports formats: "hex", "base64", "ascii7", "bytes", "auto"
/// And languages: "english", "latin", "english/bip39", "english/bip39/body"
///
/// When `wordlist_override` is "default", resolves to the language's actual
/// default wordlist (e.g., "bip39" for English) via `default_wordlist()`.
fn parse_endpoint(s: &str, wordlist_override: &str) -> glossia::Endpoint {
    match s.to_lowercase().as_str() {
        "hex" => return glossia::Endpoint::Format(glossia::DataMode::Hex),
        "base64" => return glossia::Endpoint::Format(glossia::DataMode::Base64),
        "ascii7" | "ascii" => return glossia::Endpoint::Format(glossia::DataMode::Ascii7),
        "bytes" | "bytes8" => return glossia::Endpoint::Format(glossia::DataMode::Bytes8),
        "auto" => return glossia::Endpoint::Auto,
        _ => {}
    }

    // Resolve effective wordlist for a language name.
    let resolve_wordlist = |lang: &str, explicit_wl: &str| -> String {
        if explicit_wl != "default" {
            explicit_wl.to_string()
        } else {
            let dw = glossia::generator::default_wordlist(lang);
            if dw == "default" { "default".to_string() } else { dw.to_string() }
        }
    };

    // language/wordlist/dialect syntax
    let parts: Vec<&str> = s.split('/').collect();
    match parts.len() {
        3 => glossia::Endpoint::language_full(parts[0], parts[1], parts[2]),
        2 => glossia::Endpoint::Language {
            language: parts[0].to_string(),
            wordlist: parts[1].to_string(),
            dialect: "body".to_string(),
        },
        1 => {
            let lang = parts[0];
            let wl = resolve_wordlist(lang, wordlist_override);
            glossia::Endpoint::Language {
                language: lang.to_string(),
                wordlist: wl,
                dialect: "body".to_string(),
            }
        }
        _ => glossia::Endpoint::language(s),
    }
}

/// Encode text to wordlist words using base-N conversion.
fn encode_ascii_to_words(ascii_text: &str, language: &str, wordlist: &str, dialect: &str) -> Result<(Vec<String>, glossia::DataMode), String> {
    let all_words = glossia::generator::load_payload_words_for_wordlist(language, wordlist)?;
    let tree = glossia::WordlistTree::new(all_words);

    let codec = glossia::grammar::Grammar::from_language_dialect(language, dialect)
        .map(|g| g.codec().to_string())
        .unwrap_or_else(|_| "bitpack".to_string());
    glossia::codec::encode_str_base_n(ascii_text, &tree, &codec).map_err(|e| e.to_string())
}

/// Calculate input bits based on data mode and input text
fn calculate_input_bits(input_text: &str, mode: glossia::DataMode) -> usize {
    use glossia::DataMode;
    match mode {
        DataMode::Hex => {
            // Hex: 2 chars = 1 byte = 8 bits
            (input_text.len() / 2) * 8
        }
        DataMode::Base64 => {
            // Base64: 4 chars = 3 bytes = 24 bits
            (input_text.len() / 4) * 3 * 8
        }
        DataMode::Ascii7 => {
            // ASCII-7: 1 char = 7 bits
            input_text.len() * 7
        }
        DataMode::Bytes8 => {
            // UTF-8: count actual bytes
            input_text.as_bytes().len() * 8
        }
    }
}

/// Calculate output data bits based on wordlist size and word count.
///
/// For power-of-2 wordlists (bitpack mode), the first word is a padding word,
/// so data bits = (word_count - 1) * bits_per_word (minus padding, but we
/// report the gross bits here since the padding word is metadata).
///
/// The `codec` parameter controls whether bitpack accounting applies:
/// - `"bitpack"`: first word is padding metadata, rest are data words
/// - `"base_n"`: all words are data words (base-N encoding)
fn calculate_output_bits(word_count: usize, wordlist_size: usize, codec: &str) -> Option<usize> {
    if wordlist_size == 0 || !wordlist_size.is_power_of_two() {
        return None;
    }
    let bits_per_word = wordlist_size.trailing_zeros() as usize;
    if codec == "bitpack" && wordlist_size > 1 && word_count > 0 {
        // Bitpack mode: first word is padding metadata, rest are data words
        let data_words = word_count.saturating_sub(1);
        Some(data_words * bits_per_word)
    } else {
        Some(word_count * bits_per_word)
    }
}



